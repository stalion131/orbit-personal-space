import assert from 'node:assert/strict';
import { createHash, randomUUID } from 'node:crypto';
import { zipSync, strToU8, unzipSync, strFromU8 } from 'fflate';
import { pdfFixture } from './pdf-fixture.mjs';

export async function workspaceSmoke({ api, task, setOutput, modelRequests }) {
  const path=`/api/tasks/${task.id}/ppr-workspace`;
  const call=(op,data={},status=201)=>api(path,{method:'POST',status,data:{op,revision:task.revision,...data}});
  const wire=(name,bytes)=>({name,base64:Buffer.from(bytes).toString('base64')});
  const sha=b=>createHash('sha256').update(b).digest('hex');
  await api(path,{status:403,overrideHeaders:{}});
  await api(`/api/tasks/${randomUUID()}/ppr-workspace`,{status:404});
  assert.equal((await api(path)).model,'gpt-5.6-sol');
  await api('/api/agents/ppr-status',{status:403,overrideHeaders:{}});
  await api('/api/agents/ppr-status',{method:'POST',data:{confirmConnection:false},status:400});
  setOutput({ok:true});
  assert.equal((await api('/api/agents/ppr-status',{method:'POST',data:{confirmConnection:true}})).connected,true);
  assert.ok(!JSON.stringify(modelRequests.at(-1)).includes(task.title));
  setOutput(null);
  const pdf=await call('inspect',{file:wire('source.pdf',pdfFixture())},200);
  assert.ok(pdf.file.blocks.some(b=>b.text.includes('SITE DATA 24')),'Digital PDF extraction must work in the built server.');
  const source=wire('source.txt',Buffer.from('Адрес: Учебная улица, 1'));
  const inspected=await call('inspect',{file:source},200);
  setOutput({proposals:[{field:'objectAddress',value:'Учебная улица, 1',fileHash:inspected.file.hash,blockId:inspected.file.blocks[0].id,quote:'Адрес: Учебная улица, 1',reason:'В исходном документе'},
    {field:'workType',value:'Придуманные работы',fileHash:inspected.file.hash,blockId:inspected.file.blocks[0].id,quote:'Нет такой цитаты',reason:'Неверно'}],questions:['Уточните численность.'],warnings:[]});
  const requestCount=modelRequests.length;
  await call('analyze',{files:[source]},400);
  assert.equal(modelRequests.length,requestCount);
  const beforeAddress=task.workProject.objectAddress;
  ({task}=await call('analyze',{files:[source],confirmDataTransfer:true}));
  const analysis=task.pprWorkspace.analyses.at(-1);
  assert.equal(analysis.proposals.length,1);
  assert.equal(task.workProject.objectAddress,beforeAddress,'Analysis must never silently overwrite manual fields.');
  assert.equal(modelRequests.at(-1).model,'gpt-5.6-sol');
  assert.equal(modelRequests.at(-1).reasoning.effort,'medium');
  assert.equal(modelRequests.at(-1).store,false);
  assert.ok(!JSON.stringify(modelRequests.at(-1)).includes('PRIVATE_FOLDER_DO_NOT_SEND'));
  await call('apply',{analysisId:analysis.id,fields:['workType']},400);
  ({task}=await call('apply',{analysisId:analysis.id,fields:['objectAddress']}));
  assert.equal(task.workProject.objectAddress,'Учебная улица, 1');
  await call('apply',{analysisId:analysis.id,fields:['objectAddress']},409);
  setOutput(null);
  const W='http://schemas.openxmlformats.org/wordprocessingml/2006/main';
  const paragraph=t=>`<w:p><w:r><w:t>${t}</w:t></w:r></w:p>`;
  const template=zipSync({'[Content_Types].xml':strToU8('<Types/>'),'word/document.xml':strToU8(`<w:document xmlns:w="${W}"><w:body>${paragraph('1 Общие положения')}${paragraph('Порядок организации работ определяется паспортом проекта.')}${paragraph('2 Организация работ')}${paragraph('Не менять')}<w:sectPr/></w:body></w:document>`),'word/header1.xml':strToU8(`<w:hdr xmlns:w="${W}">${paragraph('Контрольный колонтитул')}</w:hdr>`)});
  const file=wire('base.docx',template);
  const templateInfo=await call('inspect',{file},200);
  const data={file,sectionId:'general',blocks:[templateInfo.file.blocks[1].id],confirmDataTransfer:true};
  await call('generate',data,409); // applying proposals invalidates prior approval
  ({task}=await api(`/api/tasks/${task.id}/work-brief`,{method:'POST',data:{op:'approve',revision:task.revision,confirm:true,acknowledgeOpenQuestions:true}}));
  await call('generate',{...data,blocks:['unknown']},400);
  ({task}=await call('generate',data));
  const draft=task.pprDrafts.at(-1);
  assert.equal(draft.briefId,task.briefApprovals.at(-1).id);
  const assembly={file,sections:[{draftId:draft.id,start:'p-0',end:'p-2'}],confirmAssembly:true};
  await call('assemble',{...assembly,confirmAssembly:false},400);
  const assembled=await call('assemble',assembly); task=assembled.task;
  const version=task.pprWorkspace.versions.at(-1);
  const bytes=Buffer.from(assembled.file.base64,'base64');
  assert.equal(sha(bytes),version.hash);
  const parts=unzipSync(bytes);
  assert.deepEqual(parts['word/header1.xml'],unzipSync(template)['word/header1.xml']);
  parts['word/document.xml']=strToU8(strFromU8(parts['word/document.xml']).replace('Уточнить исходные данные учебного объекта.','Данные требуется запросить у подрядчика.'));
  const corrected=wire('corrected.docx',zipSync(parts));
  await call('correct',{versionId:version.id,original:file,file:corrected},409);
  ({task}=await call('correct',{versionId:version.id,original:assembled.file,file:corrected}));
  const experience=task.pprWorkspace.experience.at(-1);
  assert.equal(experience.confirmedAt,null);
  assert.equal(task.pprWorkspace.versions[0].hash,version.hash,'Original version must remain immutable.');
  assert.ok(experience.changes.some(c=>c.after.includes('подрядчика')));
  const rule='EXPLICITLY_CONFIRMED_PPR_RULE';
  ({task}=await call('confirm_experience',{experienceId:experience.id,indices:[0],rule}));
  assert.ok(task.pprWorkspace.experience.at(-1).confirmedAt);
  await call('confirm_experience',{experienceId:experience.id,indices:[0],rule},409);
  ({task}=await call('generate',data));
  assert.ok(JSON.stringify(modelRequests.at(-1)).includes(rule),'Confirmed project experience must reach SOL.');
  const reloaded=(await api('/api/tasks')).tasks.find(t=>t.id===task.id);
  assert.deepEqual(reloaded.pprWorkspace,task.pprWorkspace);
  console.log('PASS: SOL source citations, reviewed brief updates, DOCX assembly, corrected versions, confirmed experience, access and revision checks.');
  return task;
}
